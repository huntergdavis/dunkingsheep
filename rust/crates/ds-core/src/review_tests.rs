//! Tests for the accounting gates (dunk_review.py, t752/t841).

use super::*;

const PARTIAL: &str =
    "id,status\nOVL_0038_0775,partial\nOVL_0001_0001, FULL \n,partial\nOVL_0002_0002\n";

#[test]
fn only_the_partial_status_is_refused_not_presence() {
    let ids = partial_ids(PARTIAL);
    assert!(ids.contains("OVL_0038_0775"));
    assert!(
        !ids.contains("OVL_0001_0001"),
        "a `full` row is a strict credit"
    );
    assert!(
        !ids.contains("OVL_0002_0002"),
        "a row with no status column is not partial"
    );
    assert_eq!(1, ids.len(), "a blank id is skipped");
}

#[test]
fn the_header_line_is_never_an_id_and_status_is_case_and_space_insensitive() {
    assert!(partial_ids("OVL_X,partial\nOVL_Y, Partial \n").contains("OVL_Y"));
    assert!(
        !partial_ids("OVL_X,partial\n").contains("OVL_X"),
        "line 1 is the header"
    );
}

#[test]
fn the_partial_gate_quotes_the_pythons_refusal() {
    let reason = partial_gate(
        "OVL_0038_0775",
        "docs/re/partial_callee_models.csv",
        PARTIAL,
    )
    .expect("refused");
    assert_eq!(
        "OVL_0038_0775 is listed as a PARTIAL model in docs/re/partial_callee_models.csv; \
         a strict full-C credit is not owed for it. Credit it in the partial ledger \
         when its chain closes, or close the gap first.",
        reason
    );
    assert!(partial_gate("OVL_0001_0001", "t", PARTIAL).is_none());
}

#[test]
fn labelled_ids_are_the_first_column_of_non_blank_lines() {
    let ids = labelled_ids("id,kind\nOVL_A,doc\n\n  \nOVL_B , test\n");
    assert_eq!(
        ["OVL_A", "OVL_B"]
            .map(String::from)
            .into_iter()
            .collect::<BTreeSet<_>>(),
        ids
    );
}

#[test]
fn the_kind_gate_refuses_a_missing_label_and_names_the_tool() {
    let reason = kind_gate(
        "OVL_C",
        "docs/re/credit_evidence_kind.csv",
        Some("id,kind\nOVL_A,doc\n"),
    )
    .expect("refused");
    assert_eq!(
        "OVL_C has no row in docs/re/credit_evidence_kind.csv, which every strict credit \
         needs; that table is generated by tools/overlay/credit_evidence_kind.py --write. \
         The automation does not guess the label - regenerate the table in the accounting \
         branch and re-run.",
        reason
    );
    assert!(kind_gate("OVL_A", "t", Some("id,kind\nOVL_A,doc\n")).is_none());
}

#[test]
fn an_unreadable_kind_table_fails_open_like_the_python() {
    assert!(kind_gate("OVL_C", "t", None).is_none());
}
