#[derive(Default)]
struct FakeReviewMerge {
    calls: Mutex<Vec<(String, i64, String, String)>>,
    error: Mutex<Option<String>>,
}

impl ReviewRunMerge for FakeReviewMerge {
    fn merge<'a>(
        &'a self,
        repo: &'a str,
        number: i64,
        head: &'a str,
        _token: &'a str,
        task_id: &'a str,
        _report: &'a mut Value,
    ) -> ReviewFuture<'a, Result<(), String>> {
        Box::pin(async move {
            self.calls.lock().unwrap().push((
                repo.to_string(),
                number,
                head.to_string(),
                task_id.to_string(),
            ));
            match self.error.lock().unwrap().clone() {
                Some(error) => Err(error),
                None => Ok(()),
            }
        })
    }
}

#[derive(Default)]
struct FakeReviewActor {
    rows: RefCell<Vec<ReviewTaskRow>>,
    rows_error: RefCell<Option<String>>,
    notes: RefCell<Vec<TaskNote>>,
    notes_error: RefCell<Option<String>>,
    setter_error: RefCell<Option<String>>,
    note_error: RefCell<Option<String>>,
    writes: RefCell<Vec<(String, Value)>>,
}

impl ReviewTaskActor for FakeReviewActor {
    fn set_accounting_pr<'a>(
        &'a self,
        id: &'a str,
        number: i64,
    ) -> ReviewFuture<'a, Result<(), String>> {
        Box::pin(async move {
            self.writes.borrow_mut().push((
                "set_accounting_pr".into(),
                json!({"id": id, "number": number}),
            ));
            match self.setter_error.borrow().clone() {
                Some(error) => Err(error),
                None => Ok(()),
            }
        })
    }

    fn note_with_meta<'a>(
        &'a self,
        id: &'a str,
        event: &'a str,
        actor: &'a str,
        meta: &'a Value,
    ) -> ReviewFuture<'a, Result<(), String>> {
        Box::pin(async move {
            self.writes.borrow_mut().push((
                "note_with_meta".into(),
                json!({"id": id, "event": event, "actor": actor, "meta": meta}),
            ));
            match self.note_error.borrow().clone() {
                Some(error) => Err(error),
                None => Ok(()),
            }
        })
    }

    fn list_review_rows(&self) -> ReviewFuture<'_, Result<Vec<ReviewTaskRow>, String>> {
        Box::pin(async move {
            if let Some(error) = self.rows_error.borrow().clone() {
                return Err(error);
            }
            Ok(self.rows.borrow().clone())
        })
    }

    fn task_status<'a>(&'a self, id: &'a str) -> ReviewFuture<'a, Result<String, String>> {
        Box::pin(async move {
            self.rows
                .borrow()
                .iter()
                .find(|row| row.id == id)
                .map(|row| row.status.clone())
                .ok_or_else(|| format!("no task with id {id:?}"))
        })
    }

    fn cancel_review<'a>(
        &'a self,
        id: &'a str,
        _reason: &'a str,
    ) -> ReviewFuture<'a, Result<(), crate::error::DunkError>> {
        Box::pin(async move {
            let mut rows = self.rows.borrow_mut();
            let row = rows.iter_mut().find(|row| row.id == id).ok_or_else(|| {
                crate::error::DunkError::Refused(format!("no task with id {id:?}"))
            })?;
            if matches!(row.status.as_str(), "done" | "cancelled") {
                return Err(crate::error::DunkError::Refused(format!(
                    "cannot cancel {id} because it is {}",
                    row.status
                )));
            }
            row.status = "cancelled".into();
            Ok(())
        })
    }

    fn authors_of<'a>(
        &'a self,
        _repo: &'a str,
        _number: i64,
    ) -> ReviewFuture<'a, Result<Vec<String>, String>> {
        Box::pin(async { Ok(Vec::new()) })
    }

    fn notes<'a>(&'a self, _id: &'a str) -> ReviewFuture<'a, Result<Vec<TaskNote>, String>> {
        Box::pin(async move {
            if let Some(error) = self.notes_error.borrow().clone() {
                return Err(error);
            }
            Ok(self.notes.borrow().clone())
        })
    }
}

#[derive(Default)]
struct FakeReviewTransport {
    requests: Mutex<Vec<crate::github::GitHubRequest>>,
    responses: Mutex<VecDeque<Result<crate::github::GitHubResponse, String>>>,
    completion_on_request: Mutex<Option<CompletionOnRequest>>,
}

type CompletionOnRequest = (String, usize, Arc<Tasks>, String, String, String);

impl FakeReviewTransport {
    fn with_responses(
        responses: impl IntoIterator<Item = Result<crate::github::GitHubResponse, String>>,
    ) -> Self {
        Self {
            requests: Mutex::new(Vec::new()),
            responses: Mutex::new(responses.into_iter().collect()),
            completion_on_request: Mutex::new(None),
        }
    }

    fn complete_review_on_request(
        &self,
        url_fragment: &str,
        tasks: Arc<Tasks>,
        id: &str,
        by: &str,
        verdict: &str,
    ) {
        *self.completion_on_request.lock().unwrap() = Some((
            url_fragment.to_string(),
            0,
            tasks,
            id.to_string(),
            by.to_string(),
            verdict.to_string(),
        ));
    }

    fn complete_review_after_matching_requests(
        &self,
        url_fragment: &str,
        skip_matches: usize,
        tasks: Arc<Tasks>,
        id: &str,
        by: &str,
        verdict: &str,
    ) {
        *self.completion_on_request.lock().unwrap() = Some((
            url_fragment.to_string(),
            skip_matches,
            tasks,
            id.to_string(),
            by.to_string(),
            verdict.to_string(),
        ));
    }
}

impl GitHubTransport for FakeReviewTransport {
    fn send<'a>(
        &'a self,
        request: crate::github::GitHubRequest,
    ) -> crate::github::PinBoxFuture<'a, Result<crate::github::GitHubResponse, String>> {
        Box::pin(async move {
            let url = request.url.clone();
            self.requests.lock().unwrap().push(request);
            let response = self
                .responses
                .lock()
                .unwrap()
                .pop_front()
                .unwrap_or_else(|| {
                    Ok(crate::github::GitHubResponse {
                        status: 200,
                        reason: "OK".into(),
                        body: b"{}".to_vec(),
                    })
                });
            let effect = {
                let mut effect = self.completion_on_request.lock().unwrap();
                let should_run = effect.as_mut().is_some_and(|(fragment, skip, ..)| {
                    if !url.contains(fragment.as_str()) {
                        return false;
                    }
                    if *skip > 0 {
                        *skip -= 1;
                        return false;
                    }
                    true
                });
                should_run.then(|| effect.take()).flatten()
            };
            if let Some((_, _, tasks, id, by, verdict)) = effect {
                tasks
                    .set_verdict(&id, &verdict, Some(&by))
                    .await
                    .map_err(|error| error.to_string())?;
                tasks
                    .task_complete(&id, Some(&by), true)
                    .await
                    .map_err(|error| error.to_string())?;
            }
            response
        })
    }
}

fn github_response(status: u16, value: Value) -> Result<crate::github::GitHubResponse, String> {
    Ok(crate::github::GitHubResponse {
        status,
        reason: if status == 200 { "OK" } else { "Forbidden" }.into(),
        body: serde_json::to_vec(&value).unwrap(),
    })
}

