#!/usr/bin/env python3
"""Generate the Rust Unicode default-casefold map from this Python runtime."""

from __future__ import annotations

import argparse
import hashlib
import sys
import unicodedata
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "rust/crates/ds-core/src/unicode_casefold_table.rs"


def rust_string(value: str) -> str:
    escaped: list[str] = ['"']
    for char in value:
        if char == "\\":
            escaped.append("\\\\")
        elif char == '"':
            escaped.append('\\"')
        elif char == "\n":
            escaped.append("\\n")
        elif char == "\r":
            escaped.append("\\r")
        elif char == "\t":
            escaped.append("\\t")
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            escaped.append(f"\\u{{{ord(char):x}}}")
        else:
            escaped.append(char)
    escaped.append('"')
    return "".join(escaped)


def generate() -> str:
    rows: list[str] = []
    oracle = hashlib.sha256()
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        source = chr(codepoint)
        folded = source.casefold()
        oracle.update(folded.encode("utf-8"))
        oracle.update(b"\0")
        if folded != source:
            rows.append(f"    (0x{codepoint:06X}, {rust_string(folded)}),")

    return "\n".join(
        [
            "// Generated by tools/generate_unicode_casefold.py; do not edit.",
            f"// Python: {sys.version.split()[0]}",
            f"// Unicode database: {unicodedata.unidata_version}",
            "// Oracle stream: UTF-8(casefold(chr(cp))) + NUL, scalar order, surrogates skipped.",
            f'pub(crate) const PYTHON_VERSION: &str = "{sys.version.split()[0]}";',
            f'pub(crate) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
            "pub(crate) const ORACLE_SHA256: &str =",
            f'    "{oracle.hexdigest()}";',
            "pub(crate) const CASEFOLD: &[(u32, &str)] = &[",
            *rows,
            "];",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except OSError as error:
            print(f"cannot read {args.output}: {error}", file=sys.stderr)
            return 1
        if current != generated:
            print(
                f"{args.output} differs from Python {sys.version.split()[0]} "
                f"Unicode {unicodedata.unidata_version}; regenerate with this interpreter",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
