#!/usr/bin/env python3
"""Generate Unicode 16.0 Python str.isprintable ranges for Rust repr parity."""

from __future__ import annotations

import argparse
import hashlib
import sys
import unicodedata
from pathlib import Path


EXPECTED_UNICODE_VERSION = "16.0.0"
OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "rust/crates/ds-core/src/recovery_native/python_printability.rs"
)


def render() -> str:
    if unicodedata.unidata_version != EXPECTED_UNICODE_VERSION:
        raise SystemExit(
            "expected Unicode "
            f"{EXPECTED_UNICODE_VERSION}, got {unicodedata.unidata_version} "
            f"from Python {sys.version_info.major}.{sys.version_info.minor}."
            f"{sys.version_info.micro}"
        )

    ranges: list[tuple[int, int]] = []
    digest = hashlib.sha256()
    start: int | None = None
    end: int | None = None
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            if start is not None and end is not None:
                ranges.append((start, end))
                start = end = None
            continue
        printable = chr(codepoint).isprintable()
        digest.update(b"\x01" if printable else b"\x00")
        if printable:
            if start is not None and end is not None:
                ranges.append((start, end))
                start = end = None
        elif start is None:
            start = end = codepoint
        else:
            end = codepoint
    if start is not None and end is not None:
        ranges.append((start, end))

    python_version = ".".join(map(str, sys.version_info[:3]))
    lines = [
        "// Generated by tools/generate_unicode_printability.py; do not edit.",
        "#[cfg(test)]",
        f'pub(super) const PYTHON_VERSION: &str = "{python_version}";',
        "#[cfg(test)]",
        f'pub(super) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "// SHA-256 of one byte per scalar in ascending order (1 printable, 0 otherwise);",
        "// surrogate code points are skipped.",
        "#[cfg(test)]",
        "pub(super) const PRINTABILITY_SHA256: &str =",
        f'    "{digest.hexdigest()}";',
        "",
        "// Inclusive nonprintable ranges from Python str.isprintable().",
        "const NONPRINTABLE_RANGES: &[(u32, u32)] = &[",
    ]
    lines.extend(f"    (0x{first:04x}, 0x{last:04x})," for first, last in ranges)
    lines.extend(
        [
            "];",
            "",
            "pub(super) fn is_printable(character: char) -> bool {",
            "    let codepoint = character as u32;",
            "    NONPRINTABLE_RANGES",
            "        .binary_search_by(|(start, end)| {",
            "            if codepoint < *start {",
            "                std::cmp::Ordering::Greater",
            "            } else if codepoint > *end {",
            "                std::cmp::Ordering::Less",
            "            } else {",
            "                std::cmp::Ordering::Equal",
            "            }",
            "        })",
            "        .is_err()",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"generated file is stale: {OUTPUT}", file=sys.stderr)
            return 1
        print(f"verified {OUTPUT}")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
